#!/usr/bin/env node
/*
 * DoomEsque derived palette tokens.
 *
 * Each palette block in theme.css defines raw Doom colors (--doom-bg, --doom-base0..8,
 * --doom-<accent>). This script derives the semantic tokens the theme actually paints
 * with (faint/muted text, hairlines, borders, zebra stripes, readable accent text) and
 * guarantees they meet contrast targets on every palette.
 *
 *   node scripts/palette-tokens.mjs           # report contrast for every palette
 *   node scripts/palette-tokens.mjs --write   # regenerate the derived-token regions
 *   node scripts/palette-tokens.mjs --check   # CI: fail if regions are stale or targets unmet
 *
 * Derivation rule: start from the palette's own token (e.g. base3 for borders) and only
 * mix it toward the palette's ink color as far as needed to reach the target. Palettes
 * that already pass keep their original colors exactly.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const THEME = join(dirname(fileURLToPath(import.meta.url)), "..", "theme.css");
const START = "/* @derived-tokens:start — generated by scripts/palette-tokens.mjs, do not edit by hand */";
const END = "/* @derived-tokens:end */";

const ACCENTS = ["red", "orange", "yellow", "green", "teal", "blue", "magenta", "violet", "cyan"];

/** Contrast targets (WCAG 2.x ratios). */
export const TARGETS = {
	textFaint: 4.5, // smallest readable body text (counts, captions, done tasks)
	textMutedOverFaint: 1.0, // muted must sit visibly above faint
	accentText: 4.5, // accent-colored text (bold, links, tags, headers, syntax)
	hairline: 1.2, // decorative dividers (h2 rule, tab dividers)
	borderSubtle: 1.45, // container edges (cards, drawers, settings rows)
	borderStrong: 2.2, // table grid, scrollbar thumb, hover borders
	stripeMin: 1.06, // zebra rows must be visible ...
	stripeMax: 1.16, // ... but not louder than content
};

/* ---------- color math (sRGB, matches CSS color-mix(in srgb)) ---------- */
const hexToRgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const rgbToHex = (c) => "#" + c.map((v) => Math.round(v).toString(16).padStart(2, "0")).join("");
const lum = (hex) => {
	const [r, g, b] = hexToRgb(hex).map((v) => {
		v /= 255;
		return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
	});
	return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
export const contrast = (a, b) => {
	const [hi, lo] = [lum(a), lum(b)].sort((x, y) => y - x);
	return (hi + 0.05) / (lo + 0.05);
};
const mix = (from, to, t) => {
	const a = hexToRgb(from);
	const b = hexToRgb(to);
	return rgbToHex(a.map((v, i) => v + (b[i] - v) * t));
};
const minContrast = (c, surfaces) => Math.min(...surfaces.map((s) => contrast(c, s)));

/** Move `from` toward `to` in 1% steps until `ok(color)`; returns null if never satisfied. */
function nudge(from, to, ok) {
	for (let i = 0; i <= 100; i++) {
		const c = mix(from, to, i / 100);
		if (ok(c)) return c;
	}
	return null;
}

/* ---------- parsing ---------- */
export function parsePalettes(css) {
	const re = /body\.theme-(dark|light)\.doom-palette-([\w-]+)[^{]*\{([\s\S]*?)\n\}/g;
	const out = [];
	let m;
	while ((m = re.exec(css))) {
		const body = m[3];
		if (!/--doom-bg:\s*#/.test(body)) continue; // only raw palette definition blocks
		const vars = {};
		for (const [, k, v] of body.matchAll(/--doom-([\w-]+):\s*(#[0-9a-fA-F]{6})\b/g)) {
			if (!(k in vars)) vars[k] = v.toLowerCase();
		}
		const bodyStart = m.index + m[0].length - m[3].length - 2;
		out.push({ mode: m[1], name: m[2], vars, bodyStart, bodyEnd: m.index + m[0].length - 2 });
	}
	return out;
}

/* ---------- derivation ---------- */
export function derive(p) {
	const v = p.vars;
	const bg = v.bg;
	const surfaces = [v.bg, v["bg-alt"]];
	const textSurfaces = [v.bg, v["bg-alt"], v.base0, v.base1]; // body, sidebar, table header, code
	// "Ink" = whichever of fg / base8 sits furthest from the background.
	const ink = contrast(v.base8, bg) >= contrast(v.fg, bg) ? v.base8 : v.fg;
	const pure = lum(bg) < 0.18 ? "#ffffff" : "#000000";
	const warnings = [];
	const t = {};

	// Text hierarchy: faint < muted <= fg.
	const fgC = minContrast(v.fg, surfaces);
	let faintTarget = TARGETS.textFaint;
	if (fgC - 0.5 < faintTarget) {
		faintTarget = Math.max(3, fgC - 0.5);
		warnings.push(
			`fg is only ${fgC.toFixed(2)}:1 on bg/bg-alt; text-faint relaxed to ${faintTarget.toFixed(2)}:1 to stay below fg`,
		);
	}
	t["text-faint"] = nudge(v.base5, v.fg, (c) => minContrast(c, surfaces) >= faintTarget) ?? v.fg;
	const mutedSrc = p.mode === "light" ? v.base6 : v.base7;
	const mutedTarget = Math.min(minContrast(t["text-faint"], surfaces) + TARGETS.textMutedOverFaint, fgC);
	t["text-muted"] = nudge(mutedSrc, v.fg, (c) => minContrast(c, surfaces) >= mutedTarget - 1e-9) ?? v.fg;

	// Lines.
	t.hairline = nudge(v.base2, ink, (c) => minContrast(c, surfaces) >= TARGETS.hairline);
	t["border-subtle"] = nudge(v.base3, ink, (c) => minContrast(c, surfaces) >= TARGETS.borderSubtle);
	t["border-strong"] = nudge(v.base5, ink, (c) => minContrast(c, surfaces) >= TARGETS.borderStrong);

	// Zebra stripe relative to bg.
	const alt = v["bg-alt"];
	const altC = contrast(alt, bg);
	if (altC >= TARGETS.stripeMin && altC <= TARGETS.stripeMax) t.stripe = alt;
	else if (altC > TARGETS.stripeMax) t.stripe = nudge(alt, bg, (c) => contrast(c, bg) <= TARGETS.stripeMax);
	else t.stripe = nudge(bg, ink, (c) => contrast(c, bg) >= TARGETS.stripeMin + 0.02);

	// Readable accent text variants.
	for (const a of ACCENTS) {
		const raw = v[a];
		if (!raw) continue;
		const ok = (c) => minContrast(c, textSurfaces) >= TARGETS.accentText;
		t[`${a}-text`] = nudge(raw, ink, ok) ?? nudge(raw, pure, ok) ?? pure;
	}
	return { tokens: t, warnings };
}

export function verify(p, tokens) {
	const v = p.vars;
	const surfaces = [v.bg, v["bg-alt"]];
	const textSurfaces = [v.bg, v["bg-alt"], v.base0, v.base1];
	const fails = [];
	const need = (label, ratio, min) => {
		if (ratio + 1e-9 < min) fails.push(`${label} ${ratio.toFixed(2)} < ${min}`);
	};
	const fgC = minContrast(v.fg, surfaces);
	need("text-faint", minContrast(tokens["text-faint"], surfaces), Math.min(TARGETS.textFaint, Math.max(3, fgC - 0.5)));
	if (minContrast(tokens["text-muted"], surfaces) + 1e-9 < minContrast(tokens["text-faint"], surfaces))
		fails.push("text-muted is fainter than text-faint");
	need("hairline", minContrast(tokens.hairline, surfaces), TARGETS.hairline);
	need("border-subtle", minContrast(tokens["border-subtle"], surfaces), TARGETS.borderSubtle);
	need("border-strong", minContrast(tokens["border-strong"], surfaces), TARGETS.borderStrong);
	const s = contrast(tokens.stripe, v.bg);
	if (s + 1e-9 < TARGETS.stripeMin || s - 1e-9 > TARGETS.stripeMax)
		fails.push(`stripe ${s.toFixed(3)} outside [${TARGETS.stripeMin}, ${TARGETS.stripeMax}]`);
	for (const a of ACCENTS) {
		if (tokens[`${a}-text`]) need(`${a}-text`, minContrast(tokens[`${a}-text`], textSurfaces), TARGETS.accentText);
	}
	return fails;
}

function region(tokens) {
	const lines = Object.entries(tokens).map(([k, val]) => `  --doom-${k}: ${val};`);
	return `\n\n  ${START}\n${lines.join("\n")}\n  ${END}`;
}

function parseRegion(body) {
	const i = body.indexOf(START);
	if (i < 0) return null;
	const j = body.indexOf(END, i);
	const tokens = {};
	for (const [, k, val] of body.slice(i, j).matchAll(/--doom-([\w-]+):\s*(#[0-9a-f]{6});/g)) tokens[k] = val;
	return tokens;
}

/* ---------- main ---------- */
function main() {
	const mode = process.argv.includes("--write") ? "write" : process.argv.includes("--check") ? "check" : "report";
	let css = readFileSync(THEME, "utf8");
	const palettes = parsePalettes(css);
	let failed = false;

	// Write back-to-front so earlier offsets stay valid.
	for (const p of [...palettes].reverse()) {
		const { tokens, warnings } = derive(p);
		const body = css.slice(p.bodyStart, p.bodyEnd);
		const existing = parseRegion(body);
		const fails = verify(p, tokens);
		const label = `${p.mode}/${p.name}`.padEnd(26);

		if (mode === "write") {
			const stripped = body.replace(/\n\n {2}\/\* @derived-tokens:start[\s\S]*?@derived-tokens:end \*\//, "");
			css = css.slice(0, p.bodyStart) + stripped.replace(/\s*$/, "") + region(tokens) + css.slice(p.bodyEnd);
		}
		if (mode === "check") {
			const stale = !existing || JSON.stringify(existing) !== JSON.stringify(tokens);
			if (stale) {
				failed = true;
				console.error(`${label} derived tokens are stale — run: node scripts/palette-tokens.mjs --write`);
			}
			if (existing) {
				const f = verify(p, existing);
				if (f.length) {
					failed = true;
					console.error(`${label} ${f.join("; ")}`);
				}
			}
		}
		if (fails.length) {
			failed = true;
			console.error(`${label} cannot meet targets: ${fails.join("; ")}`);
		}
		if (mode === "report") {
			const v = p.vars;
			const sf = [v.bg, v["bg-alt"]];
			const changed = ACCENTS.filter((a) => tokens[`${a}-text`] && tokens[`${a}-text`] !== v[a]);
			console.log(
				`${label} faint ${minContrast(tokens["text-faint"], sf).toFixed(2)}  muted ${minContrast(tokens["text-muted"], sf).toFixed(2)}  ` +
					`hair ${minContrast(tokens.hairline, sf).toFixed(2)}  subtle ${minContrast(tokens["border-subtle"], sf).toFixed(2)}  ` +
					`strong ${minContrast(tokens["border-strong"], sf).toFixed(2)}  stripe ${contrast(tokens.stripe, v.bg).toFixed(3)}  ` +
					`adjusted accents: ${changed.join(",") || "none"}`,
			);
		}
		for (const w of warnings) console.warn(`${label} warning: ${w}`);
	}

	if (mode === "write") writeFileSync(THEME, css);
	if (mode === "check" && !failed) console.log(`All ${palettes.length} palettes meet contrast targets and derived tokens are current.`);
	process.exit(failed ? 1 : 0);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
