#!/usr/bin/env node
/*
 * DoomEsque derived palette tokens.
 *
 * Each palette block in theme.css defines raw Doom colors (--doom-bg, --doom-base0..8,
 * --doom-<accent>). This script derives the semantic tokens the theme actually paints
 * with (faint/muted text, hairlines, borders, zebra stripes, readable accent text) and
 * guarantees they meet contrast targets on every palette.
 *
 *   node scripts/palette-tokens.mjs           # report contrast for every palette
 *   node scripts/palette-tokens.mjs --write   # regenerate the derived-token regions
 *   node scripts/palette-tokens.mjs --check   # CI: fail if regions are stale or targets unmet
 *
 * Derivation rule: start from the palette's own token (e.g. base3 for borders) and only
 * mix it toward the palette's ink color as far as needed to reach the target. Palettes
 * that already pass keep their original colors exactly.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const THEME = join(dirname(fileURLToPath(import.meta.url)), "..", "theme.css");
const START = "/* @derived-tokens:start — generated by scripts/palette-tokens.mjs, do not edit by hand */";
const END = "/* @derived-tokens:end */";

const ACCENTS = ["red", "orange", "yellow", "green", "teal", "blue", "magenta", "violet", "cyan"];

/** Contrast targets (WCAG 2.x ratios). */
export const TARGETS = {
	textNormal: 7, // body text on the editor and sidebars (WCAG AAA)
	textFaint: 4.5, // smallest readable body text (counts, captions, done tasks)
	comment: 4.5, // code comments on code blocks and the editor
	lineNumber: 3, // editor gutter line numbers (secondary UI text)
	onAccent: 4.5, // text on solid accent fills (primary buttons, selected search match, badges)
	highlight: 4.5, // body text on ==highlighted== text
	textMutedOverFaint: 1.0, // muted must sit visibly above faint
	accentText: 4.5, // accent-colored text (bold, links, tags, headers, syntax)
	hairline: 1.2, // decorative dividers (h2 rule, tab dividers)
	borderSubtle: 1.45, // container edges (cards, drawers, settings rows)
	borderStrong: 2.2, // table grid, scrollbar thumb, hover borders
	stripeMin: 1.12, // zebra rows must be clearly visible ...
	stripeMax: 1.2, // ... but not louder than content
	tableBorder: 3.0, // table grid vs body and striped rows (WCAG 1.4.11 non-text contrast)
	tableHeader: 1.3, // header row background vs body background
	tableHeaderHover: 1.45, // hovered header cell vs body background
};

/* ---------- color math (sRGB, matches CSS color-mix(in srgb)) ---------- */
const hexToRgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const rgbToHex = (c) => "#" + c.map((v) => Math.round(v).toString(16).padStart(2, "0")).join("");
const lum = (hex) => {
	const [r, g, b] = hexToRgb(hex).map((v) => {
		v /= 255;
		return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
	});
	return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
export const contrast = (a, b) => {
	const [hi, lo] = [lum(a), lum(b)].sort((x, y) => y - x);
	return (hi + 0.05) / (lo + 0.05);
};
const mix = (from, to, t) => {
	const a = hexToRgb(from);
	const b = hexToRgb(to);
	return rgbToHex(a.map((v, i) => v + (b[i] - v) * t));
};
const minContrast = (c, surfaces) => Math.min(...surfaces.map((s) => contrast(c, s)));
/** `color` at `alpha` composited over `bg` (what rgba(color, alpha) looks like on bg). */
export const over = (color, bg, alpha) => mix(bg, color, alpha);

/** Accents with a solid fill variant (primary/warning buttons, selected search match). */
const FILLS = ["blue", "cyan", "red", "yellow", "green"];
/** Callout background tint (theme.css: rgba(callout, 0.065), 0.1 in light mode). */
const calloutTint = (mode) => (mode === "light" ? 0.1 : 0.065);

/** Surfaces body-level text sits on: editor, sidebars, tab bar. */
const uiSurfaces = (v) => [v.bg, v["bg-alt"], v.base0];
/**
 * Surfaces accent text sits on: the UI surfaces, code, table stripes and its own callout tint, plus
 * where specific accents appear: blue (links, status bar) on hover backgrounds, and yellow (tag text)
 * on the yellow tag tints.
 */
const accentSurfaces = (p, stripe, accent) => {
	const v = p.vars;
	const list = [...uiSurfaces(v), v.base1, stripe, over(v[accent], v.bg, calloutTint(p.mode))];
	if (accent === "blue") list.push(v.base2);
	if (accent === "yellow") list.push(over(v.yellow, v.bg, 0.12), over(v.yellow, v.bg, 0.22));
	return list;
};
/** Text colour for solid accent fills: the darkest background in dark palettes, white in light ones. */
const onAccentFor = (p) => (p.mode === "dark" ? (lum(p.vars.base0) < lum(p.vars.bg) ? p.vars.base0 : p.vars.bg) : "#ffffff");

/** Move `from` toward `to` in 1% steps until `ok(color)`; returns null if never satisfied. */
function nudge(from, to, ok) {
	for (let i = 0; i <= 100; i++) {
		const c = mix(from, to, i / 100);
		if (ok(c)) return c;
	}
	return null;
}

/** `--accent-h/s/l` values (hue in degrees, saturation and lightness in %) for a hex colour. */
function accentHsl(hex) {
	const [r, g, b] = hexToRgb(hex).map((x) => x / 255);
	const max = Math.max(r, g, b);
	const min = Math.min(r, g, b);
	const l = (max + min) / 2;
	const d = max - min;
	let h = 0;
	let sat = 0;
	if (d !== 0) {
		sat = d / (1 - Math.abs(2 * l - 1));
		if (max === r) h = ((g - b) / d) % 6;
		else if (max === g) h = (b - r) / d + 2;
		else h = (r - g) / d + 4;
		h = (h * 60 + 360) % 360;
	}
	const round1 = (x) => Math.round(x * 10) / 10;
	return { "accent-h": `${round1(h)}`, "accent-s": `${round1(sat * 100)}%`, "accent-l": `${round1(l * 100)}%` };
}

/* ---------- parsing ---------- */
export function parsePalettes(css) {
	const re = /body\.theme-(dark|light)\.doom-palette-([\w-]+)[^{]*\{([\s\S]*?)\n\}/g;
	const out = [];
	let m;
	while ((m = re.exec(css))) {
		const body = m[3];
		if (!/--doom-bg:\s*#/.test(body)) continue; // only raw palette definition blocks
		const vars = {};
		for (const [, k, v] of body.matchAll(/--doom-([\w-]+):\s*(#[0-9a-fA-F]{6})\b/g)) {
			if (!(k in vars)) vars[k] = v.toLowerCase();
		}
		const bodyStart = m.index + m[0].length - m[3].length - 2;
		out.push({ mode: m[1], name: m[2], vars, bodyStart, bodyEnd: m.index + m[0].length - 2 });
	}
	return out;
}

/* ---------- derivation ---------- */
export function derive(p) {
	const v = p.vars;
	const bg = v.bg;
	const surfaces = uiSurfaces(v);
	// "Ink" = whichever of fg / base8 sits furthest from the background.
	const ink = contrast(v.base8, bg) >= contrast(v.fg, bg) ? v.base8 : v.fg;
	const pure = lum(bg) < 0.18 ? "#ffffff" : "#000000";
	const warnings = [];
	const t = {};

	// Text hierarchy: faint < muted <= fg.
	const fgC = minContrast(v.fg, surfaces);
	let faintTarget = TARGETS.textFaint;
	if (fgC - 0.5 < faintTarget) {
		faintTarget = Math.max(3, fgC - 0.5);
		warnings.push(
			`fg is only ${fgC.toFixed(2)}:1 on bg/bg-alt; text-faint relaxed to ${faintTarget.toFixed(2)}:1 to stay below fg`,
		);
	}
	t["text-faint"] = nudge(v.base5, v.fg, (c) => minContrast(c, surfaces) >= faintTarget) ?? v.fg;
	const mutedSrc = p.mode === "light" ? v.base6 : v.base7;
	const mutedTarget = Math.min(minContrast(t["text-faint"], surfaces) + TARGETS.textMutedOverFaint, fgC);
	t["text-muted"] = nudge(mutedSrc, v.fg, (c) => minContrast(c, surfaces) >= mutedTarget - 1e-9) ?? v.fg;

	// Lines.
	t.hairline = nudge(v.base2, ink, (c) => minContrast(c, surfaces) >= TARGETS.hairline);
	t["border-subtle"] = nudge(v.base3, ink, (c) => minContrast(c, surfaces) >= TARGETS.borderSubtle);
	t["border-strong"] = nudge(v.base5, ink, (c) => minContrast(c, surfaces) >= TARGETS.borderStrong);

	// Zebra stripe relative to bg, shaded in the same direction as bg-alt (darker in every palette).
	const alt = v["bg-alt"];
	const altC = contrast(alt, bg);
	const shade = p.mode === "dark" ? "#000000" : ink;
	if (altC >= TARGETS.stripeMin && altC <= TARGETS.stripeMax) t.stripe = alt;
	else if (altC > TARGETS.stripeMax) t.stripe = nudge(alt, bg, (c) => contrast(c, bg) <= TARGETS.stripeMax);
	else t.stripe = nudge(bg, shade, (c) => contrast(c, bg) >= TARGETS.stripeMin + 0.01) ?? nudge(bg, ink, (c) => contrast(c, bg) >= TARGETS.stripeMin + 0.01);

	// Table header row: background tinted with the palette's primary accent, clearly set apart from the body.
	t["table-header-bg"] = nudge(bg, v.blue, (c) => contrast(c, bg) >= TARGETS.tableHeader);
	t["table-header-bg-hover"] = nudge(bg, v.blue, (c) => contrast(c, bg) >= TARGETS.tableHeaderHover);

	// Table grid: readable against plain rows, striped rows and the header.
	const tableRows = [v.bg, t.stripe];
	t["table-border"] = nudge(v.base5, ink, (c) => minContrast(c, tableRows) >= TARGETS.tableBorder) ?? ink;

	// Header label colour: the primary accent, adjusted only as far as the tinted header requires.
	const headerSurfaces = [t["table-header-bg"], t["table-header-bg-hover"]];
	t["table-header-text"] =
		nudge(v.blue, ink, (c) => minContrast(c, headerSurfaces) >= TARGETS.accentText) ??
		nudge(v.blue, pure, (c) => minContrast(c, headerSurfaces) >= TARGETS.accentText) ??
		pure;

	// Readable accent text variants: on every UI surface, code and hover backgrounds, table stripes,
	// and the accent's own tints (callouts, tags).
	for (const a of ACCENTS) {
		const raw = v[a];
		if (!raw) continue;
		const ok = (c) => minContrast(c, accentSurfaces(p, t.stripe, a)) >= TARGETS.accentText;
		t[`${a}-text`] = nudge(raw, ink, ok) ?? nudge(raw, pure, ok) ?? pure;
	}

	// Code comments: the palette's comment grey, lifted only as far as code blocks require.
	const codeSurfaces = [v.base1, v.bg, v["bg-alt"]];
	t.comment = nudge(v.base5, v.fg, (c) => minContrast(c, codeSurfaces) >= TARGETS.comment) ?? v.fg;

	// Gutter line numbers: dim, but legible.
	t["line-number"] = nudge(v.base4, v.fg, (c) => minContrast(c, [v.bg, v["bg-alt"]]) >= TARGETS.lineNumber) ?? v.fg;

	// Solid accent fills (primary/warning buttons, selected search match) and the text on them.
	const onAccent = onAccentFor(p);
	t["on-accent"] = onAccent;
	const away = p.mode === "dark" ? "#ffffff" : "#000000";
	for (const a of FILLS) {
		t[`${a}-fill`] = nudge(v[a], away, (c) => contrast(onAccent, c) >= TARGETS.onAccent) ?? away;
	}

	// Obsidian's own accent (--accent-h/s/l drives --color-accent: canvas focus, selection outlines,
	// and other native rings) follows the palette's blue instead of Obsidian's default purple.
	Object.assign(t, accentHsl(v.blue));

	// ==Highlight== background: the palette's yellow at up to 26%, less if body text would suffer.
	t["highlight-bg"] = v.bg;
	for (let i = 26; i >= 6; i--) {
		const c = over(v.yellow, v.bg, i / 100);
		if (contrast(v.fg, c) >= TARGETS.highlight) {
			t["highlight-bg"] = c;
			break;
		}
	}
	return { tokens: t, warnings };
}

export function verify(p, tokens) {
	const v = p.vars;
	const surfaces = uiSurfaces(v);
	const fails = [];
	const need = (label, ratio, min) => {
		if (ratio + 1e-9 < min) fails.push(`${label} ${ratio.toFixed(2)} < ${min}`);
	};
	const fgC = minContrast(v.fg, surfaces);
	need("fg", minContrast(v.fg, [v.bg, v["bg-alt"]]), TARGETS.textNormal);
	need("text-faint", minContrast(tokens["text-faint"], surfaces), Math.min(TARGETS.textFaint, Math.max(3, fgC - 0.5)));
	if (minContrast(tokens["text-muted"], surfaces) + 1e-9 < minContrast(tokens["text-faint"], surfaces))
		fails.push("text-muted is fainter than text-faint");
	need("hairline", minContrast(tokens.hairline, surfaces), TARGETS.hairline);
	need("border-subtle", minContrast(tokens["border-subtle"], surfaces), TARGETS.borderSubtle);
	need("border-strong", minContrast(tokens["border-strong"], surfaces), TARGETS.borderStrong);
	const s = contrast(tokens.stripe, v.bg);
	if (s + 1e-9 < TARGETS.stripeMin || s - 1e-9 > TARGETS.stripeMax)
		fails.push(`stripe ${s.toFixed(3)} outside [${TARGETS.stripeMin}, ${TARGETS.stripeMax}]`);
	need("table-border", minContrast(tokens["table-border"], [v.bg, tokens.stripe]), TARGETS.tableBorder);
	need("table-header-bg", contrast(tokens["table-header-bg"], v.bg), TARGETS.tableHeader);
	need("table-header-bg-hover", contrast(tokens["table-header-bg-hover"], v.bg), TARGETS.tableHeaderHover);
	need("fg on table-header-bg", contrast(v.fg, tokens["table-header-bg"]), TARGETS.textFaint);
	need("table-header-text", minContrast(tokens["table-header-text"], [tokens["table-header-bg"], tokens["table-header-bg-hover"]]), TARGETS.accentText);
	for (const a of ACCENTS) {
		if (tokens[`${a}-text`]) need(`${a}-text`, minContrast(tokens[`${a}-text`], accentSurfaces(p, tokens.stripe, a)), TARGETS.accentText);
	}
	need("comment", minContrast(tokens.comment, [v.base1, v.bg, v["bg-alt"]]), TARGETS.comment);
	need("line-number", minContrast(tokens["line-number"], [v.bg, v["bg-alt"]]), TARGETS.lineNumber);
	for (const a of FILLS) need(`on-accent on ${a}-fill`, contrast(tokens["on-accent"], tokens[`${a}-fill`]), TARGETS.onAccent);
	need("fg on highlight-bg", contrast(v.fg, tokens["highlight-bg"]), TARGETS.highlight);
	if (contrast(tokens["highlight-bg"], v.bg) < 1.05) fails.push("highlight-bg is indistinguishable from bg");
	if (v["modeline-fg"] && v["modeline-bg"]) need("modeline", contrast(v["modeline-fg"], v["modeline-bg"]), TARGETS.textFaint);
	return fails;
}

function region(tokens) {
	const lines = Object.entries(tokens).map(([k, val]) => `  --doom-${k}: ${val};`);
	return `\n\n  ${START}\n${lines.join("\n")}\n  ${END}`;
}

function parseRegion(body) {
	const i = body.indexOf(START);
	if (i < 0) return null;
	const j = body.indexOf(END, i);
	const tokens = {};
	for (const [, k, val] of body.slice(i, j).matchAll(/--doom-([\w-]+):\s*([^;]+);/g)) tokens[k] = val.trim();
	return tokens;
}

/* ---------- main ---------- */
function main() {
	const mode = process.argv.includes("--write") ? "write" : process.argv.includes("--check") ? "check" : "report";
	let css = readFileSync(THEME, "utf8");
	const palettes = parsePalettes(css);
	let failed = false;

	// Write back-to-front so earlier offsets stay valid.
	for (const p of [...palettes].reverse()) {
		const { tokens, warnings } = derive(p);
		const body = css.slice(p.bodyStart, p.bodyEnd);
		const existing = parseRegion(body);
		const fails = verify(p, tokens);
		const label = `${p.mode}/${p.name}`.padEnd(26);

		if (mode === "write") {
			const stripped = body.replace(/\n\n {2}\/\* @derived-tokens:start[\s\S]*?@derived-tokens:end \*\//, "");
			css = css.slice(0, p.bodyStart) + stripped.replace(/\s*$/, "") + region(tokens) + css.slice(p.bodyEnd);
		}
		if (mode === "check") {
			const stale = !existing || JSON.stringify(existing) !== JSON.stringify(tokens);
			if (stale) {
				failed = true;
				console.error(`${label} derived tokens are stale — run: node scripts/palette-tokens.mjs --write`);
			}
			if (existing) {
				const f = verify(p, existing);
				if (f.length) {
					failed = true;
					console.error(`${label} ${f.join("; ")}`);
				}
			}
		}
		if (fails.length) {
			failed = true;
			console.error(`${label} cannot meet targets: ${fails.join("; ")}`);
		}
		if (mode === "report") {
			const v = p.vars;
			const sf = [v.bg, v["bg-alt"]];
			const changed = ACCENTS.filter((a) => tokens[`${a}-text`] && tokens[`${a}-text`] !== v[a]);
			console.log(
				`${label} faint ${minContrast(tokens["text-faint"], sf).toFixed(2)}  muted ${minContrast(tokens["text-muted"], sf).toFixed(2)}  ` +
					`hair ${minContrast(tokens.hairline, sf).toFixed(2)}  subtle ${minContrast(tokens["border-subtle"], sf).toFixed(2)}  ` +
					`strong ${minContrast(tokens["border-strong"], sf).toFixed(2)}  stripe ${contrast(tokens.stripe, v.bg).toFixed(3)}  ` +
					`adjusted accents: ${changed.join(",") || "none"}`,
			);
		}
		for (const w of warnings) console.warn(`${label} warning: ${w}`);
	}

	if (mode === "write") writeFileSync(THEME, css);
	if (mode === "check" && !failed) console.log(`All ${palettes.length} palettes meet contrast targets and derived tokens are current.`);
	process.exit(failed ? 1 : 0);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
